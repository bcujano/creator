export function fechaLarga(fecha: Date, idioma: Idioma) {
  return fecha.toLocaleDateString(idioma === 'en' ? 'en-US' : 'es-EC', {
    day: 'numeric',
    month: 'long',
    year: 'numeric',
    timeZone: 'America/Guayaquil',
  })
}
